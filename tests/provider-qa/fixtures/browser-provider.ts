import { CodingAgentError } from '../../../src/domain/agent-error.js';
import type { CodingAgent, CodingAgentRequest, CodingAgentResponse, RunEvent } from '../../../src/domain/types.js';
import { createNodeBase } from '../../../src/domain/defaults.js';
import { LocalProviderConnectionService } from '../../../src/adapters/providers/connection-service.js';

/** Test-only provider registry. It never calls an external model or reports live verification. */
export async function createBrowserProviderFixture(dataDirectory: string): Promise<LocalProviderConnectionService> {
  return LocalProviderConnectionService.open(dataDirectory, { createAgent: () => new BrowserFixtureAgent() });
}

class BrowserFixtureAgent implements CodingAgent {
  async *execute(request: CodingAgentRequest, signal: AbortSignal): AsyncIterable<RunEvent | { type: 'response'; response: CodingAgentResponse }> {
    if (request.prompt.startsWith('Connection verification only.')) {
      yield { type: 'response', response: { operations: [], summary: 'Fixture verification only. This is not live provider evidence.' } };
      return;
    }
    if (request.prompt === '__fixture_quota__') throw new CodingAgentError('provider.quota', 'Fixture quota exhausted. No fallback was attempted.');
    if (request.prompt === '__fixture_wait__') {
      if (!signal.aborted) await new Promise<void>(resolve => signal.addEventListener('abort', () => resolve(), { once: true }));
      return;
    }
    const pageId = request.documentFragment.page?.id;
    if (!pageId) throw new Error('Fixture request did not contain an active page.');
    yield { type: 'state', runId: request.runId, state: 'RUNNING', at: new Date().toISOString() };
    yield { type: 'response', response: { operations: [fixtureTextOperation(pageId)], summary: 'Fixture provider generated one editable text node.' } };
  }

  async cancel(): Promise<void> {}
  async getStatus(runId: string) { return { runId, state: 'SUCCEEDED' as const }; }
}

function fixtureTextOperation(pageId: string) {
  const base = createNodeBase('provider-fixture-title', 'Fixture provider title');
  return {
    type: 'node.create' as const,
    pageId,
    index: 0,
    node: { ...base, kind: 'text' as const, text: 'Generated by provider fixture', textStyle: {} },
  };
}
