import { expect, test } from '@playwright/test';

test.use({ video: 'on' });
test.skip(process.env.CODEX_DESIGN_LIVE === '1', 'Provider connection flows use deterministic fixtures and are excluded from live Codex runs.');

const credentialSentinel = 'provider-e2e-credential-sentinel';

test('headed fixture provider flow stores a credential privately, routes the explicit selection, and renders committed design', async ({ page }) => {
  const apiResponses: string[] = [];
  page.on('response', async response => {
    if (response.url().includes('/api/')) apiResponses.push(await response.text());
  });

  await page.goto('/');
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  await page.getByLabel('Create a project', { exact: true }).fill('Provider success fixture');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Your projects' })).toBeHidden();
  await expect(page.getByRole('region', { name: 'Design canvas' })).toContainText('Page 1');

  const providerMenu = page.locator('.provider-menu > summary');
  await providerMenu.click();
  const connectionPanel = page.getByRole('region', { name: 'AI connection' });
  await expect(connectionPanel).toBeVisible();
  await page.getByLabel('Provider connection').selectOption('codex');
  await page.getByLabel('Authentication source').selectOption('openai-api-key');
  await page.getByLabel('Connection name').fill('Fixture Codex API');
  await page.getByLabel('Credential').fill(credentialSentinel);
  await page.getByRole('button', { name: 'Add connection' }).click();
  await expect(connectionPanel.locator('.provider-panel__message[role="status"]')).toContainText('Verify it to check current access');
  await page.getByText('Custom model ID', { exact: true }).click();
  await page.getByLabel('Model', { exact: true }).fill('gpt-6.1-sol');
  await page.getByLabel('Model effort').selectOption('low');
  await expect(connectionPanel.locator('.provider-panel__hint[role="status"]')).toContainText('unknown');

  await page.getByRole('button', { name: 'Test connection' }).click();
  await expect(connectionPanel.locator('.provider-panel__hint[role="status"]')).toContainText('This model and effort are verified for this connection.');
  await expect(connectionPanel.locator('.provider-panel__status')).toHaveText('Verified');
  await providerMenu.click();

  await page.getByLabel('Describe a design or edit').fill('Create an editable fixture text label');
  const startResponsePromise = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/runs');
  await page.getByRole('button', { name: 'Generate design' }).click();
  const startResponse = await startResponsePromise;
  expect(startResponse.ok(), `provider run start response: ${await startResponse.text()}`).toBe(true);
  await expect(page.locator('.canvas-node[data-node-kind="text"]')).toContainText('Generated by provider fixture', { timeout: 15_000 });
  await expect(page.getByText('Design saved at revision 1')).toBeVisible({ timeout: 15_000 });

  const runsResponse = await page.request.get('/api/runs');
  expect(runsResponse.ok()).toBe(true);
  const runs = (await runsResponse.json() as { runs: Array<Record<string, unknown>> }).runs;
  expect(runs[0]).toMatchObject({
    providerSelection: {
      providerId: 'codex',
      authSource: 'openai-api-key',
      connectionId: expect.any(String),
      modelId: 'gpt-6.1-sol',
      effort: 'low',
      verificationStatus: 'verified',
      policy: 'manual',
    },
    committedRevision: 1,
    state: 'SUCCEEDED',
  });

  const exportResponse = await page.request.post('/api/export', {
    headers: { origin: 'http://127.0.0.1:5174' },
    data: { target: 'native' },
  });
  expect(exportResponse.ok()).toBe(true);
  apiResponses.push(await exportResponse.text());
  expect(apiResponses.join('\n')).not.toContain(credentialSentinel);
  const browserStorage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  expect(browserStorage).not.toContain(credentialSentinel);
  expect(await page.locator('body').innerText()).not.toContain(credentialSentinel);
});

 test('headed fixture preflight, quota failure and cancellation preserve the document and selected route', async ({ page }) => {
  const created = await page.request.post('/api/project/new', { headers: { origin: 'http://127.0.0.1:5174' }, data: { name: 'Provider failure fixture' } });
  expect(created.status()).toBe(201);
  await page.goto('/');
  const menu = page.locator('.provider-menu > summary');
  await menu.click();
  await page.getByLabel('Provider connection').selectOption('codex-local');
  await page.getByRole('button', { name: 'Test connection', exact: true }).click();
  await expect(page.locator('.provider-panel__hint[role="status"]')).toContainText('This model and effort are verified');
  await menu.click();
  const rejected = await page.request.post('/api/runs', { headers: { origin: 'http://127.0.0.1:5174' }, data: { prompt: 'Rejected fixture', selectedNodeIds: [], expectedRevision: 0, providerSelection: { connectionId: 'codex-local', modelId: 'unverified-model', effort: 'low' } } });
  expect(rejected.status()).toBe(422);
  for (const [prompt, state] of [['__fixture_quota__', 'Run failed'], ['__fixture_wait__', 'Cancelled']] as const) {
    await page.getByLabel('Describe a design or edit').fill(prompt);
    await page.getByRole('button', { name: 'Generate design', exact: true }).click();
    if (state === 'Cancelled') {
      const cancel = page.getByRole('button', { name: 'Cancel run', exact: true });
      await expect(cancel).toBeVisible();
      await cancel.click();
    }
    await expect(page.locator('.run-sidebar__state')).toHaveText(state);
    const project = (await (await page.request.get('/api/project')).json()).project;
    expect(project.document.revision).toBe(0);
    expect(Object.keys(project.document.nodes)).toHaveLength(0);
  }
  const runs = (await (await page.request.get('/api/runs')).json()).runs;
  expect(runs).toHaveLength(2);
  expect(new Set(runs.map((run: { id: string }) => run.id)).size).toBe(2);
  expect(runs.every((run: { providerSelection: { connectionId: string } }) => run.providerSelection.connectionId === 'codex-local')).toBe(true);
  await page.reload();
  await expect(page.locator('.run-sidebar__state')).toHaveText('Cancelled');
});
